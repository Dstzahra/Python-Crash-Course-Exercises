"""
Source: Python Crash Course (3rd Edition)
Chapter: 04
Topic: Simple Statistics with a List of Numbers

Description:
This example demonstrates how to use the min(), max(), and sum()
functions to find simple statistics from a list of numbers.
"""

# Create a list of numbers.
digits = [1, 2, 3, 4, 5, 6, 7, 8, 9, 0]

# Find the smallest number in the list.
print(min(digits))

# Find the largest number in the list.
print(max(digits))

# Find the sum of all numbers in the list.
print(sum(digits))