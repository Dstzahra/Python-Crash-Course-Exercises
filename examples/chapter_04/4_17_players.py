"""
Source: Python Crash Course (3rd Edition)
Chapter: 04
Topic: Slicing a List

Description:
This example demonstrates how to access specific parts of a list
using slicing.
"""

players = ['charles', 'martina', 'michael', 'florence', 'eli']

# Print the first three players.
print(players[0:3])

# Print the second, third, and fourth players.
print(players[1:4])