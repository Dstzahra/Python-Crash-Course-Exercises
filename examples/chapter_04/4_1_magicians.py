"""
Source: Python Crash Course (3rd Edition)
Chapter: 04
Topic: Looping Through an Entire List

Description:
This example demonstrates how to use a for loop to go through
each item in a list and print its value.
"""

magicians = ['Alice', 'David', 'Carolina']

# Loop through each magician in the list.
for magician in magicians:

    # Print the current magician's name.
    print(magician)