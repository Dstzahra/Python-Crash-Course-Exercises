"""
Source: Python Crash Course (3rd Edition)
Chapter: 02
Topic: Integers and Floats

Description:
This example demonstrates how integers and floating-point numbers
work together in Python. It shows that operations involving floats
often return a floating-point result.
"""

# Division with integers returns a float
print(4 / 2)


# Operations between integers and floats return floats
print(1 + 2.0)
print(2 * 3.0)
print(3.0 ** 2)