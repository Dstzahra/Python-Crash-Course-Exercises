# Addition
print(2 + 3)

# Subtraction
print(3 - 2)

# Multiplication
print(2 * 3)

# Division
print(3 / 2)


# Exponents
print(3 ** 2)
print(3 ** 3)
print(10 ** 6)


# Order of operations
print(2 + 3 * 4)
print((2 + 3) * 4)