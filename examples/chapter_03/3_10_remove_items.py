"""
Source: Python Crash Course (3rd Edition)
Chapter: 03
Topic: Removing Items from a List

Description:
This example demonstrates how to remove items from a list
using the del statement and index positions.
"""

motorcycles = ["honda", "yamaha", "suzuki"]
print(motorcycles)

# Remove the first motorcycle from the list using its index.
del motorcycles[0]
print(motorcycles)

motorcycles = ["honda", "yamaha", "suzuki"]
print(motorcycles)

# Remove the second motorcycle from the list using its index.
del motorcycles[1]
print(motorcycles)