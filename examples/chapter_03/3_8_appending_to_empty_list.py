"""
Source: Python Crash Course (3rd Edition)
Chapter: 03
Topic: Appending Elements to an Empty List

Description:
This example demonstrates how to build a list dynamically
by adding elements to an empty list using append().
"""

motorcycles = []

# Add the first motorcycle to the list.
motorcycles.append('honda')

# Add the second motorcycle to the list.
motorcycles.append('yamaha')

# Add the third motorcycle to the list.
motorcycles.append('suzuki')

# Print the completed list.
print(motorcycles)