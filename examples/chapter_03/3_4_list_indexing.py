"""
Source: Python Crash Course (3rd Edition)
Chapter: 03
Topic: Index Positions Start at 0, Not 1

Description:
This example demonstrates how to access individual values
from a list using positive and negative indexes.
"""

bicycles = ['trek', 'cannondale', 'redline', 'specialized']

# Access the second item in the list.
print(bicycles[1])

# Access the fourth item in the list.
print(bicycles[3])

# Access the last item in the list.
print(bicycles[-1])